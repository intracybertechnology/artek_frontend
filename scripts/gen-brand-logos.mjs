/**
 * scripts/gen-brand-logos.mjs
 *
 * Scans public/images/brand-logos/ and generates src/data/brandLogos.generated.ts
 * with a { slug: "filename.ext" } map.  Run before build/dev to keep the map
 * fresh — there is no hand-written list to maintain.
 *
 *   node scripts/gen-brand-logos.mjs
 */
import { readdir } from "node:fs/promises";
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { brandGroups, slugify } from "../src/data/catalog.ts";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const LOGOS_DIR = path.join(ROOT, "public/images/brand-logos");
const OUT_FILE = path.join(ROOT, "src/data/brandLogos.generated.ts");

/** Accepted extensions in priority order (svg > png > webp > jpg > jpeg). */
const EXT_PRIORITY = ["svg", "png", "webp", "jpg", "jpeg"];
const EXT_SET = new Set(EXT_PRIORITY);

/** File-name slug: name without extension, lowercased, spaces/underscores → hyphens. */
function fileSlug(filename) {
  const ext = path.extname(filename);
  const base = filename.slice(0, -ext.length);
  return base.toLowerCase().replace(/[\s_]+/g, "-");
}

/** Every brand slug from brandGroups — used to warn about unmatched files. */
const brandSlugs = new Set(brandGroups.flatMap((g) => g.brands.map((b) => slugify(b))));

async function main() {
  const files = await readdir(LOGOS_DIR);

  // Group files by their computed slug
  const bySlug = new Map();
  for (const file of files) {
    const ext = path.extname(file).slice(1).toLowerCase();
    if (!EXT_SET.has(ext)) {
      console.log(`SKIP  ${file}  (extension .${ext} not accepted)`);
      continue;
    }
    const slug = fileSlug(file);
    if (!bySlug.has(slug)) bySlug.set(slug, []);
    bySlug.get(slug).push(file);
  }

  const map = {};
  const warnings = [];

  for (const [slug, candidates] of bySlug) {
    // Sort by extension priority (svg first, jpeg last)
    candidates.sort(
      (a, b) =>
        EXT_PRIORITY.indexOf(path.extname(a).slice(1).toLowerCase()) -
        EXT_PRIORITY.indexOf(path.extname(b).slice(1).toLowerCase()),
    );

    const chosen = candidates[0];
    map[slug] = chosen;

    // Warn about duplicates (same slug from different files)
    for (let i = 1; i < candidates.length; i++) {
      warnings.push(`Duplicate slug "${slug}": kept "${chosen}", ignored "${candidates[i]}"`);
    }

    // Warn about files that match no brand
    if (!brandSlugs.has(slug)) {
      warnings.push(`No brand matches slug "${slug}" (file: ${chosen})`);
    }
  }

  // Generate the TypeScript file (sorted alphabetically)
  const entries = Object.entries(map)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([slug, file]) => `  ${JSON.stringify(slug)}: ${JSON.stringify(file)},`)
    .join("\n");

  const content = `/* AUTO-GENERATED by scripts/gen-brand-logos.mjs — do not edit by hand.
 * Maps brand slug → logo filename for every file in public/images/brand-logos/.
 * Run \`npm run gen:logos\` after adding or removing logo files.
 */
export const BRAND_LOGO_FILES: Readonly<Record<string, string>> = {
${entries}
};
`;

  writeFileSync(OUT_FILE, content, "utf8");

  const matched = Object.keys(map).filter((s) => brandSlugs.has(s)).length;
  console.log(`\nGenerated ${path.relative(ROOT, OUT_FILE)} — ${Object.keys(map).length} files, ${matched} matched brands.`);

  if (warnings.length) {
    console.log("\nWarnings:");
    for (const w of warnings) console.log(`  ${w}`);
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
