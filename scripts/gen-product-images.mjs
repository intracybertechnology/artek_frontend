/**
 * scripts/gen-product-images.mjs
 *
 * Scans public/images/products/<group-slug>/ (subfolders only — files directly
 * in public/images/products are category images) and generates
 * src/data/productImages.generated.ts with a
 * { "group-slug/product-slug": "/images/products/<group-slug>/<file>" } map.
 * Run before build/dev to keep the map fresh — there is no hand-written list
 * to maintain.
 *
 *   node scripts/gen-product-images.mjs
 */
import { readdir } from "node:fs/promises";
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { productGroups, slugify } from "../src/data/catalog.ts";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const IMAGES_DIR = path.join(ROOT, "public/images/products");
const OUT_FILE = path.join(ROOT, "src/data/productImages.generated.ts");

/** Accepted extensions in priority order (webp > png > jpg). */
const EXT_PRIORITY = ["webp", "png", "jpg"];
const EXT_SET = new Set(EXT_PRIORITY);

/** File-name slug: name without extension, lowercased, spaces/underscores → hyphens. */
function fileSlug(filename) {
  const ext = path.extname(filename);
  const base = filename.slice(0, -ext.length);
  return base.toLowerCase().replace(/[\s_]+/g, "-");
}

/** Every product as "group-slug/product-slug" → display name, grouped for reporting. */
const productsByGroup = productGroups.map((group) => ({
  slug: group.slug,
  title: group.title,
  items: group.items.map((item) => ({ name: item, slug: slugify(item) })),
}));
const allProductKeys = new Set(productsByGroup.flatMap((g) => g.items.map((i) => `${g.slug}/${i.slug}`)));

async function main() {
  // Group files by "group-slug/product-slug" so the same product can arrive in
  // several formats — the extension priority picks one.
  const byKey = new Map();

  const groupDirs = (await readdir(IMAGES_DIR, { withFileTypes: true }))
    .filter((d) => d.isDirectory());

  for (const groupDir of groupDirs) {
    const files = await readdir(path.join(IMAGES_DIR, groupDir.name));
    for (const file of files) {
      const ext = path.extname(file).slice(1).toLowerCase();
      if (!EXT_SET.has(ext)) {
        console.log(`SKIP  ${groupDir.name}/${file}  (extension .${ext} not accepted)`);
        continue;
      }
      const key = `${groupDir.name}/${fileSlug(file)}`;
      if (!byKey.has(key)) byKey.set(key, []);
      byKey.get(key).push(file);
    }
  }

  const map = {};
  const warnings = [];

  for (const [key, candidates] of byKey) {
    candidates.sort(
      (a, b) =>
        EXT_PRIORITY.indexOf(path.extname(a).slice(1).toLowerCase()) -
        EXT_PRIORITY.indexOf(path.extname(b).slice(1).toLowerCase()),
    );

    const chosen = candidates[0];
    const [groupSlug] = key.split("/");
    map[key] = `/images/products/${groupSlug}/${chosen}`;

    // Warn about duplicates (same product from different files)
    for (let i = 1; i < candidates.length; i++) {
      warnings.push(`Duplicate product "${key}": kept "${chosen}", ignored "${candidates[i]}"`);
    }

    // Warn about files that match no product
    if (!allProductKeys.has(key)) {
      warnings.push(`No product matches "${key}" (file: ${chosen})`);
    }
  }

  // Generate the TypeScript file (sorted alphabetically)
  const entries = Object.entries(map)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([key, file]) => `  ${JSON.stringify(key)}: ${JSON.stringify(file)},`)
    .join("\n");
  const content = `/* AUTO-GENERATED by scripts/gen-product-images.mjs — do not edit by hand.
 * Maps "group-slug/product-slug" → image path for every file in
 * public/images/products/<group-slug>/ (category images at the root are not listed).
 * Run \`npm run gen:images\` after running \`npm run optimize:images\`.
 */
export const PRODUCT_IMAGE_FILES: Readonly<Record<string, string>> = {
${entries}
};
`;

  writeFileSync(OUT_FILE, content, "utf8");

  // ── Reporting ──
  const total = productsByGroup.reduce((n, g) => n + g.items.length, 0);
  const covered = productsByGroup.reduce(
    (n, g) => n + g.items.filter((i) => Object.prototype.hasOwnProperty.call(map, `${g.slug}/${i.slug}`)).length,
    0,
  );
  console.log(`\nGenerated ${path.relative(ROOT, OUT_FILE)} — ${Object.keys(map).length} files.`);
  console.log(`${covered} of ${total} products have an image`);

  const missing = productsByGroup
    .map((g) => ({
      title: g.title,
      items: g.items.filter((i) => !Object.prototype.hasOwnProperty.call(map, `${g.slug}/${i.slug}`)),
    }))
    .filter((g) => g.items.length > 0);
  if (missing.length) {
    console.log("\nProducts without an image:");
    for (const g of missing) {
      console.log(`  ${g.title}: ${g.items.map((i) => i.name).join(", ")}`);
    }
  }

  if (warnings.length) {
    console.log("\nWarnings:");
    for (const w of warnings) console.log(`  ${w}`);
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
